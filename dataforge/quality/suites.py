EMAIL_RE = r"^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$"


def R(id_, dataset, check, severity, description, column=None, rationale="", **params) -> Rule:
    return Rule(
        id=id_,
        dataset=dataset,
        check=check,
        severity=severity,
        description=description,
        column=column,
        params=params,
        rationale=rationale,
    )


