"""The rule catalogue: every validation rule applied in the silver layer.

Naming: <dataset>.<rule>. Columns ending in `_t` are typed casts of the raw string
column and columns ending in `_n` are normalised strings, both produced by the silver
job before validation (see dataforge/spark/silver/common.py).

`python scripts/export_quality_rules.py` renders this catalogue to docs/data_quality_rules.md.
"""

